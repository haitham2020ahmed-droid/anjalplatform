import Link from "next/link";
import { ReportProblem } from "@/components/questions/report-problem";
import { notFound } from "next/navigation";
import { AppShell } from "@/components/app-shell";
import { ActionForm } from "@/components/admin/action-form";
import { card, field, h2 } from "@/components/admin/styles";
import { getActor, repo, requireActor } from "@/server/auth/next";
import { can } from "@/server/auth/rbac";
import { getQuestion } from "@/server/admin/questions";
import { flagsOfQuestion } from "@/server/admin/questions-list";
import { aiReviewAction, deleteOneQuestionAction, questionStepAction } from "../../actions";
import { unflagOneAction } from "../list-actions";
import { QuestionEditor } from "../question-editor";
import { editorOptions } from "../editor-data";
import { MiniAction } from "@/components/admin/mini-action";
import { LineIcon } from "@/components/ui/line-icon";
import { attachmentNodes } from "@/server/curriculum-map/questions";
import { deletionRequestOf } from "@/server/admin/question-requests";
import { requestDeletionAction, restoreEditAction } from "../request-actions";
import { editLogOf, editRequestOf } from "@/server/admin/question-edits";

const ACTION_LABEL: Record<string, string> = {
  "question.ai.generate": "Generated by AI", "question.ai.approve": "Approved (AI draft)", "question.ai.reject": "Rejected (AI draft)",
  "question.create": "Created", "question.update": "Edited", "question.update_published": "Edited (published)", "question.submit": "Sent for review", "question.reject": "Sent back", "question.publish": "Published", "question.archive": "Archived", "question.revise": "New version created",
  "question.edit.request": "Change sent to the admin", "question.edit.approve": "Change approved", "question.edit.reject": "Change rejected", "question.edit.restore": "Earlier version restored",
  "question.unflag": "Flags cleared", "question.repair": "Repaired automatically", "question.remap": "Put under its skill", "question.classify": "Skill chosen",
};
const STATUS_CHIP: Record<string, string> = { DRAFT: "bg-slate-100 text-slate-700", UNDER_REVIEW: "bg-amber-100 text-amber-900", PUBLISHED: "bg-teal-100 text-teal-900", ARCHIVED: "bg-slate-200 text-slate-600" };

export default async function QuestionPage({ params, searchParams }: { params: Promise<{ questionId: string }>; searchParams?: Promise<{ msg?: string }> }) {
  const flash = searchParams ? (await searchParams).msg : undefined;
  const actor = await requireActor({ permission: "questions:read" });
  const me = (await getActor())!.user;
  const { questionId } = await params;
  const d = await getQuestion(repo, actor, questionId).catch(() => null);
  if (!d) notFound();
  const row = await repo.findUnique("Question", { id: questionId });
  const delReq = row ? deletionRequestOf(row) : null;
  const editReq = row ? editRequestOf(row) : null;
  const editLog = row ? editLogOf(row) : [];
  const isAdminUser = actor.role === "SCHOOL_ADMIN" || actor.role === "SUPER_ADMIN";
  const [{ skills, standards, grades }, places, flags] = await Promise.all([
    editorOptions(repo, actor.schoolId!), attachmentNodes(repo, actor.schoolId!), isAdminUser ? flagsOfQuestion(repo, actor, questionId) : Promise.resolve([]),
  ]);
  const openFlags = flags.filter((f) => f.status === "OPEN");
  // ✏️ a teacher may change any question: the change waits for the admin (students keep the current version)
  const requestMode = actor.role === "TEACHER" && !d.canEdit && d.status !== "ARCHIVED";
  // ✏️ an admin may change a published question students answered: saved and published as a new version
  const anyway = d.canEditAnyway && !d.openRevision;
  const step = (s: string, text: string, opts: { note?: "required" | "optional"; danger?: boolean } = {}) => (
    <ActionForm action={questionStepAction} submit={text} danger={opts.danger} className="space-y-2">
      <input type="hidden" name="questionId" value={d.id} /><input type="hidden" name="step" value={s} />
      {opts.note && <textarea name="note" rows={2} maxLength={1000} required={opts.note === "required"} placeholder={opts.note === "required" ? "What needs to change / why" : "Note (optional)"} className={field} />}
    </ActionForm>
  );
  const pill = "inline-flex items-center gap-1.5 rounded-xl px-4 py-2 text-sm font-semibold";
  return (
    <AppShell name={String(me.displayName)}>
      <p><Link href="/admin/questions" className="inline-flex items-center gap-1 text-brand-teal hover:underline"><span aria-hidden="true" className="inline-block rtl:rotate-180">‹</span> Questions</Link></p>
      <h1 className="mt-2 flex flex-wrap items-center gap-3 text-3xl font-bold text-brand-navy">Question <span className="font-mono text-lg text-slate-500">{d.ref}</span>
        <span className={`rounded-full px-3 py-1 text-sm font-semibold ${STATUS_CHIP[d.status] ?? ""}`}>{d.status.replace("_", " ").toLowerCase()}</span></h1>
      <p className="mt-1 text-slate-600">Version {d.version}{d.origin === "AI_GENERATED" ? " · AI-drafted" : ""}{d.input.cognitiveLevel ? ` · cognitive level: ${d.input.cognitiveLevel}` : ""}{d.answered ? " · answered by students" : ""}{d.revisionOf ? <> · new version of <Link className="text-brand-teal hover:underline" href={`/admin/questions/${d.revisionOf}`}>the earlier one</Link></> : null}</p>

      {flash && <p role="status" className="animate-pop mt-4 rounded-2xl bg-teal-50 px-4 py-3 text-teal-900 ring-1 ring-teal-200">{flash}</p>}
      {d.replacedBy && (
        <p role="status" className="mt-4 flex flex-wrap items-center gap-2 rounded-2xl bg-slate-100 px-4 py-3 text-slate-800 ring-1 ring-slate-200">
          <LineIcon name="layers" className="h-5 w-5" />This old version was replaced. Students' past answers stay with it.
          <Link href={`/admin/questions/${d.replacedBy}`} className="font-semibold text-brand-navy underline">Open the new version</Link>
        </p>
      )}
      {d.openRevision && (
        <p role="status" className="mt-4 flex flex-wrap items-center gap-2 rounded-2xl bg-sky-50 px-4 py-3 text-sky-950 ring-1 ring-sky-200" data-testid="open-revision">
          <LineIcon name="pen" className="h-5 w-5" />A new version of this question is being edited. Students see this one until it is published.
          <Link href={`/admin/questions/${d.openRevision}`} className="font-semibold text-brand-navy underline">Open the new version</Link>
        </p>
      )}

      {d.canReviewAi && (
        <section className={card}>
          <h2 className={h2}>Review This AI-Drafted Question</h2>
          <p className="text-sm text-slate-600">Check the question, the correct answer and the explanation below (edit if needed), then approve it for students or reject it.</p>
          <div className="mt-3 grid gap-4 sm:grid-cols-2">
            <ActionForm action={aiReviewAction} submit="Approve for students" className="space-y-2">
              <input type="hidden" name="questionId" value={d.id} /><input type="hidden" name="decision" value="approve" />
            </ActionForm>
            <ActionForm action={aiReviewAction} submit="Reject" danger className="space-y-2">
              <input type="hidden" name="questionId" value={d.id} /><input type="hidden" name="decision" value="reject" />
              <textarea name="reason" rows={2} required maxLength={500} placeholder="Why is it rejected?" className={field} />
            </ActionForm>
          </div>
        </section>
      )}

      <section className={card}>
        <h2 className={h2}>Next Step</h2>
        <div className="mt-3 grid gap-4 sm:grid-cols-2">
          {d.status === "DRAFT" && can(actor, "questions:publish") && step("publish", d.revisionOf ? "Publish (replaces the earlier version everywhere)" : "Publish")}
          {d.status === "DRAFT" && d.canEdit && step("submit", "Send for review")}
          {d.canReview && step("approve", d.revisionOf ? "Publish (replaces the earlier version everywhere)" : "Approve and publish", { note: "optional" })}
          {d.canReview && step("reject", "Send back to the author", { note: "required", danger: true })}
          {d.status === "UNDER_REVIEW" && !d.canReview && <p className="text-slate-600">Waiting for a reviewer{d.mine ? " (another person must approve your own question)" : ""}.</p>}
          {d.status === "PUBLISHED" && can(actor, "questions:edit") && !d.openRevision && step("revise", "Make a new version")}
          {d.status === "PUBLISHED" && d.openRevision && <Link href={`/admin/questions/${d.openRevision}`} className={`${pill} justify-self-start bg-brand-navy text-white`}><LineIcon name="pen" className="h-4 w-4" />Open the new version</Link>}
          {d.status !== "ARCHIVED" && can(actor, "questions:publish") && step("archive", "Archive", { note: "required", danger: true })}
          {isAdminUser && can(actor, "questions:publish") && (
            <div className="rounded-xl p-4 ring-1 ring-red-200">
              <p className="flex items-center gap-1.5 font-semibold text-red-800"><LineIcon name="alert" className="h-4 w-4" />Delete</p>
              <p className="mt-1 text-sm text-slate-600">{d.answered ? "The question disappears from the whole platform: the bank, every practice pool and every test or set that has not started. Students' past answers stay in their records and reports." : "No student has answered it: it is deleted for good."}</p>
              <div className="mt-2"><MiniAction action={deleteOneQuestionAction} fields={{ questionId: d.id }} label="Delete question" tone="danger"
                confirm={d.answered ? "Delete this question from the whole platform? It leaves the bank, every pool and every test or set that has not started. Students' past answers stay in their records." : "Delete this question permanently? This cannot be undone."} /></div>
            </div>
          )}
          {actor.role === "TEACHER" && <div className="rounded-xl p-4 ring-1 ring-rose-200"><ReportProblem questionId={d.id} /></div>}
          {actor.role === "TEACHER" && d.status !== "ARCHIVED" && (
            <div className="rounded-xl p-4 ring-1 ring-red-200">
              <p className="font-semibold text-red-800">Request deletion</p>
              {delReq ? <p className="mt-1 text-sm text-slate-700">Requested by {delReq.byName} on {delReq.at.slice(0, 10)}: “{delReq.reason}”. An admin will decide.</p> : (
                <form action={requestDeletionAction} className="mt-2 space-y-2">
                  <input type="hidden" name="questionId" value={d.id} />
                  <textarea name="reason" required minLength={5} maxLength={500} rows={2} placeholder="Why should it be removed?" className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm" />
                  <button className="rounded-xl bg-red-50 px-4 py-2 text-sm font-semibold text-red-800 ring-1 ring-red-200 hover:bg-red-100">Send the request to the admin</button>
                </form>
              )}
            </div>
          )}
          {delReq && actor.role !== "TEACHER" && <p className="rounded-xl bg-red-50 px-3 py-2 text-sm text-red-800">Deletion requested by {delReq.byName}: “{delReq.reason}”. <Link href="/admin/questions/requests" className="font-semibold underline">Decide</Link></p>}
          {d.status === "PUBLISHED" && d.canEdit && <p className="text-sm text-slate-600">No student has answered this question yet, so you can edit it directly below.</p>}
          {d.status === "PUBLISHED" && !d.canEdit && !anyway && <p className="text-sm text-slate-600">Students have answered this question: its statistics belong to this exact wording. “Make a new version” makes an editable copy; publishing it replaces this one everywhere.</p>}
        </div>
      </section>

      {isAdminUser && flags.length > 0 && (
        <section className={card} data-testid="question-flags">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <h2 className={`${h2} flex items-center gap-2`}><LineIcon name="flag" className="h-5 w-5 text-rose-700" />Flags ({openFlags.length} open)</h2>
            {openFlags.length > 0 && can(actor, "questions:publish") && <MiniAction action={unflagOneAction} fields={{ questionId: d.id }} label="Clear the flags" confirm="Clear every open flag of this question?" />}
          </div>
          <ul className="mt-2 divide-y divide-slate-100 text-sm">{flags.map((f) => (
            <li key={f.id} className="py-2">
              <span className="font-semibold text-brand-navy"><bdi>{f.by}</bdi></span> <span className="text-slate-500">({f.role === "STUDENT" ? "student" : f.role === "TEACHER" ? "teacher" : "staff"}) · {f.at.slice(0, 10)}</span>
              {f.status !== "OPEN" && <span className="ms-2 rounded bg-slate-100 px-1.5 text-xs text-slate-600">{f.status === "FIXED" ? "fixed" : "cleared"}</span>}
              <p className="text-slate-800">{f.reason}{f.note ? <>: “{f.note}”</> : null}</p>
            </li>
          ))}</ul>
        </section>
      )}

      <p className="mt-4 flex flex-wrap items-center gap-1.5 rounded-xl bg-indigo-50 px-4 py-2 text-sm text-indigo-950 ring-1 ring-indigo-200"><LineIcon name="compass" className="h-4 w-4" />NWEA MAP: {d.map.area ? <><b>{d.map.test}</b> · <b>{d.map.area}</b> <span className="text-indigo-700">({d.map.source === "ADMIN" ? "set by an admin" : d.map.source === "IMPORT" ? "from the import file" : d.map.source === "TEXT" ? "read from the wording — please check" : d.map.source === "STANDARD" ? "from its standard" : d.map.source === "SKILL" ? "from its skill (Mechanics)" : d.map.source === "SKILL_STANDARD" ? "from its skill's standard" : "from its skill category"})</span>
      {/* 🔧 improvement (Oct 2026): TEXT and AI are the two lowest-confidence auto-classification sources (classifyQuestion's
          fallback cascade) — flag them so an admin scanning questions notices which ones were never confirmed by a human. */}
      {(d.map.source === "TEXT" || d.map.source === "AI") && <span className="rounded-full bg-amber-100 px-2 py-0.5 text-xs font-semibold text-amber-800 ring-1 ring-amber-300">⚠ Needs review</span>}</> : "not classified yet"}</p>
      {editReq && (
        <p data-testid="edit-waiting" className="mt-4 rounded-xl bg-amber-50 px-4 py-2 text-sm text-amber-950 ring-1 ring-amber-200">
          A change by <b>{editReq.byName}</b> ({editReq.at.slice(0, 10)}) is waiting for the admin. Students still see the version below.
          {isAdminUser && <> <Link href="/admin/questions/requests" className="font-semibold underline">Review it</Link></>}
        </p>
      )}
      {requestMode && <p className="mt-4 rounded-xl bg-sky-50 px-4 py-2 text-sm text-sky-950 ring-1 ring-sky-200">You can change this question. When you save, your change goes to the admin; it applies for every student after the admin approves it.</p>}
      {anyway && <p className="mt-4 rounded-xl bg-amber-50 px-4 py-2 text-sm text-amber-950 ring-1 ring-amber-200" data-testid="edit-anyway"><b>Edit anyway.</b> Students have answered this question. When you save, your change becomes a new version and is published at once: it replaces this one everywhere, and students' past answers stay with this version.</p>}
      <section className={card}>
        <h2 className={h2}>{d.canEdit || requestMode || anyway ? "Edit" : "Question"}</h2>
        <div className="mt-3"><QuestionEditor questionId={d.id} initial={editReq && editReq.by === actor.userId ? editReq.input : d.input} skills={skills} standards={standards} readOnly={!d.canEdit && !requestMode && !anyway} saveLabel={anyway ? "Save and publish as a new version" : undefined} curriculum={can(actor, "curriculum:edit") ? { grades } : undefined} places={places.map((p) => ({ code: p.code, grade: p.grade, unit: p.unit, path: p.path }))} /></div>
      </section>

      {editLog.length > 0 && (
        <section className={card} data-testid="edit-log">
          <h2 className={h2}>Edit Log</h2>
          <ol className="mt-2 space-y-2 text-sm">
            {editLog.map((e) => (
              <li key={e.at} className="rounded-xl bg-slate-50 p-3 ring-1 ring-slate-200">
                <p><span className="text-slate-500">{e.at.slice(0, 16).replace("T", " ")}</span> · {e.kind === "RESTORE" ? "Restored" : "Changed"} by <bdi>{e.byName}</bdi> · approved by <bdi>{e.approvedByName}</bdi></p>
                <p className="mt-1 text-slate-600" data-content lang="en">Before: “{e.stemBefore}”</p>
                {isAdminUser && (
                  <form action={restoreEditAction} className="mt-2">
                    <input type="hidden" name="questionId" value={d.id} /><input type="hidden" name="at" value={e.at} />
                    <button className="inline-flex items-center gap-1 rounded-xl px-3 py-1.5 text-xs font-semibold text-brand-navy ring-1 ring-slate-300 hover:bg-white"><LineIcon name="retry" className="h-3.5 w-3.5" />Restore the version before this change</button>
                  </form>
                )}
              </li>
            ))}
          </ol>
        </section>
      )}

      <section className={card}>
        <h2 className={h2}>History</h2>
        <ol className="mt-2 space-y-1 text-sm">
          {d.history.map((h, i) => <li key={i}><span className="text-slate-500">{h.at.slice(0, 16).replace("T", " ")}</span> · {ACTION_LABEL[h.action] ?? h.action} · <bdi>{h.by || "the platform"}</bdi>{h.note ? <> · <em>“{h.note}”</em></> : null}</li>)}
        </ol>
      </section>
    </AppShell>
  );
}
