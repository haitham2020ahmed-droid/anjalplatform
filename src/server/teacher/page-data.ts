/**
 * ⚡ Teacher pages' data with independent reads together (Update 42B). Same functions and results as before; each
 * function still checks the teacher's access itself.
 *   class page   overview + the unit list together, then the heat map + the assignment list together
 *   student page the student detail (access check) first, then every section at once
 */
import type { Actor } from "../auth/rbac";
import type { Repo, Row } from "../seeding/repo";
import { classAssignments } from "./assignments";
import { classOverview, masteryGrid, studentDetail } from "./queries";
import { studentLearningPath } from "../student/learning-path";
import { resolvePeriod } from "../../analytics/periods";
import { loadCalendar } from "../analytics/calendar";
import { studentAnalytics } from "../analytics/reports";
import { mapComparison } from "../analytics/map-compare";
import { staffFamilyReports } from "../reports/family-reports";
import { buildProfiles, profilesOf } from "../insights/student-profile";
import { tierLine } from "../tiers/views";
import { studentProfileExtras } from "./student-profile";

export async function teacherClassData(repo: Repo, actor: Actor, classId: string, unit: string | undefined) {
  const range = { from: new Date(Date.now() - 365 * 86_400_000), to: new Date() };
  // read-only on GET (readiness C-1/I-1): skill-support flags and alerts are generated by the daily job
  const unitsOf = async (): Promise<Row[]> => {
    const klass = (await repo.findUnique("Class", { id: classId }))!;
    const cur = (await repo.findMany("Curriculum", { gradeId: klass.gradeId, isActive: true }))[0];
    // a grade with no curriculum yet (e.g. a new Grade 11): no units, the rest of the class page still works
    return cur ? (await repo.findMany("Unit", { curriculumId: cur.id })).sort((a, b) => Number(a.number) - Number(b.number)) : [];
  };
  // the overview checks access first: the unit list is only used once it has passed
  const [o, units] = await Promise.all([classOverview(repo, actor, classId, range), unitsOf().catch((e) => e as Error)]);
  if (units instanceof Error) throw units;
  const unitId = unit && units.some((u) => u.id === unit) ? unit : units[0] ? String(units[0].id) : null;
  const [grid, assignments] = await Promise.all([unitId ? masteryGrid(repo, actor, classId, unitId) : Promise.resolve(null), classAssignments(repo, actor, classId)]);
  return { o, units, unitId, grid, assignments };
}

export async function teacherStudentData(repo: Repo, actor: Actor, studentId: string) {
  const d = await studentDetail(repo, actor, studentId); // access checked inside
  const st = (await repo.findUnique("Student", { id: studentId }))!;
  const [member, analytics, profile, tier, reports, path, mapCompare, extras] = await Promise.all([
    repo.findMany("ClassMembership", { studentId, leftAt: null }).then((r) => r[0]),
    loadCalendar(repo, String(st.schoolId)).then((cal) => studentAnalytics(repo, actor, studentId, resolvePeriod("SCHOOL_YEAR", cal))),
    // the student profile (built nightly; built now if this student has none yet)
    (async () => {
      let p = (await profilesOf(repo, [studentId])).get(studentId) ?? null;
      if (!p) { await buildProfiles(repo, String(st.schoolId), new Date(), [studentId]).catch(() => 0); p = (await profilesOf(repo, [studentId])).get(studentId) ?? null; }
      return p;
    })(),
    tierLine(repo, studentId).catch(() => null),
    staffFamilyReports(repo, actor, { studentId }).catch(() => []),
    studentLearningPath(repo, actor, studentId),
    mapComparison(repo, actor, studentId),
    // the one-page profile (UI reorg Phase 3): My Work, plans, tests, MAP, answers, time
    studentProfileExtras(repo, actor, studentId),
  ]);
  return { d, st, member, analytics, profile, tier, reports, path, mapCompare, extras };
}
