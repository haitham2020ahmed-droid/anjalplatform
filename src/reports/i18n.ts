const DICT: Record<Locale, Record<LabelKey, string>> = { en: EN, ar: AR };

export function t(locale: Locale, key: LabelKey, vars: Record<string, string | number> = {}): string {
  return DICT[locale][key].replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** Every key exists in both languages (checked by a test; the type also enforces it). */
export function missingTranslations(): LabelKey[] {
  return (Object.keys(EN) as LabelKey[]).filter((k) => !AR[k] || !AR[k].trim());
}

