const pick = (l: Locale, pair: [string, string] | undefined, fallback: string) => (pair ? pair[l === "ar" ? 1 : 0] : fallback);

/** Band code (MASTERED) or English band label (Mastered) → localized label. */
export function bandLabel(l: Locale, band: string): string {
  const code = band.toUpperCase();
  return pick(l, BANDS[code], band);
}

