export const domainCodeFromLabel = (label: string) => Object.entries(DOMAINS).find(([, v]) => v[0] === label)?.[0] ?? null;

const ORDINALS_AR = ["", "الأول", "الثاني", "الثالث", "الرابع", "الخامس", "السادس", "السابع", "الثامن", "التاسع", "العاشر", "الحادي عشر", "الثاني عشر"];

export function gradeName(l: Locale, level: number): string {
  if (l === "ar") return ORDINALS_AR[level] ? `الصف ${ORDINALS_AR[level]}` : `الصف ${level}`;
  return `Grade ${level}`;
}

// -------------------------------------------------------------- formatting

const intlLocale = (l: Locale, digits: Digits) => (l === "ar" ? `ar-SA-u-ca-gregory-nu-${digits}` : "en-GB-u-ca-gregory");

export interface Fmt {
  locale: Locale;
  digits: Digits;
  num(v: number | null | undefined, maxFraction?: number): string;
  pct(v: number | null | undefined): string;
  signed(v: number | null | undefined): string;
  date(v: Date | string | null | undefined): string;
  dateTime(v: Date): string;
}

export function formatter(locale: Locale, digits: Digits = "latn"): Fmt {
  const loc = intlLocale(locale, locale === "ar" ? digits : "latn");
  const none = t(locale, "none");
  const asDate = (v: Date | string) => (v instanceof Date ? v : new Date(v.length === 10 ? `${v}T00:00:00Z` : v));
  return {
    locale,
    digits,
    num: (v, maxFraction = 1) => (v === null || v === undefined || Number.isNaN(v) ? none : new Intl.NumberFormat(loc, { maximumFractionDigits: maxFraction }).format(v)),
    pct: (v) => (v === null || v === undefined ? none : new Intl.NumberFormat(loc, { style: "percent", maximumFractionDigits: 0 }).format(v / 100)),
    signed: (v) => (v === null || v === undefined ? none : new Intl.NumberFormat(loc, { maximumFractionDigits: 1, signDisplay: "exceptZero" }).format(v)),
    date: (v) => (v === null || v === undefined || v === "" ? none : new Intl.DateTimeFormat(loc, { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" }).format(asDate(v))),
    dateTime: (v) => new Intl.DateTimeFormat(loc, { day: "numeric", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit", timeZone: "Asia/Riyadh" }).format(v),
  };
}

/**
 * Localized period label. Period.label from the analytics layer is English; this
 * re-derives it from the period's name so Arabic reports never show English periods.
 * Term and year names are the school's own data ("Term 1", "2026-2027") and are kept.
 */
export function periodLabel(l: Locale, p: Period, fmt = formatter(l)): string {
  switch (p.name) {
    case "LAST_7_DAYS":
    case "LAST_30_DAYS":
      return t(l, `period.${p.name}`);
    case "SEMESTER":
      return t(l, p.label === "Second semester" ? "period.secondSemester" : "period.firstSemester");
    case "SCHOOL_YEAR":
      return p.label === "Last 12 months" ? t(l, "period.last12") : t(l, "period.year", { name: p.label });
    case "TERM":
      return /^Last 30 days$/.test(p.label) ? t(l, "period.LAST_30_DAYS") : t(l, "period.term", { name: p.label });
    case "CUSTOM":
      return t(l, "period.custom", { from: fmt.date(p.from), to: fmt.date(p.to) });
  }
}
