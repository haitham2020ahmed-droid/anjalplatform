/**
 * Report language: English or Arabic labels, number and date formatting.
 *
 * Rules
 *  - Only the report's own words are translated. Curriculum content (skill names,
 *    CCSS standard text) stays in English, exactly as in the school's curriculum,
 *    and the Arabic report says so in its notes.
 *  - Dates are Gregorian in both languages. (Intl's default calendar for "ar-SA" is
 *    Umm al-Qura, which would silently change every date, so the calendar is forced.)
 *  - Digits are Western (0-9) by default in both languages, matching MAP RIT scores,
 *    student numbers and the school's spreadsheets. "arab" switches the Arabic
 *    report to Arabic-Indic digits.
 *  - Official values (MAP RIT, percentile) are never reformatted beyond digits.
 */
